#!/bin/sh
set -eu

HARNESS_DIR=$(cd "$(dirname "$0")" && pwd)
REPO_DIR=$(cd "$HARNESS_DIR/../../.." && pwd)
CASES_DIR=$REPO_DIR/e2e/ext/fixtures
SPEC_DIR=$REPO_DIR/spec/payload
REGISTRY=$REPO_DIR/src/core/test/spec-fixtures.util.ts
SUITES="coherent extract"
EXIT_STALE=1
EXIT_USAGE=2

suite_defs() {
  cat "$HARNESS_DIR/payload-sections.jq" "$HARNESS_DIR/$1-payload.jq"
}

golden() {
  jq --arg suite "$1" "$(suite_defs "$1")
{
  area: \"payload\",
  operation: \$suite,
  description: \"Generated by e2e/ext/conformance/spec-payloads.sh from e2e/ext/fixtures/\(\$suite)-conformance.json with the conformance harness's jq payload builder. Do not edit; run make spec-payloads.\",
  cases: [
    .cases[]
    | {
        id: \"payload-\(\$suite)-conformance-\(.id)\",
        description: \"The \(\$suite) conformance case \(.id) builds the payload the jq harness sends.\",
        input: ({ facts: .state, response } + (if \$suite == \"coherent\" then { claim } else { target, type, mode } end)),
        expect: { text: (. | ${1}_payload) }
      }
  ]
}" "$CASES_DIR/$1-conformance.json"
}

fixture_mismatches() {
  jq -r "$(suite_defs "$1")
.cases[]
| select((.input + { state: ((.input.facts // []) + (.input.callFacts // [])) } | ${1}_payload) != .expect.text)
| .id" "$SPEC_DIR/$1.json"
}

write_goldens() {
  for suite in $SUITES; do
    golden "$suite" > "$SPEC_DIR/$suite-conformance.json"
  done
  (cd "$REPO_DIR" && npx prettier --log-level warn --write spec/payload/*-conformance.json)
}

unregistered_fixtures() {
  (cd "$REPO_DIR" && find spec -name '*.json' ! -name fixture.schema.json | sort) | while read -r file; do
    grep -q "'../../../$file'" "$REGISTRY" || echo "$file"
  done
}

check_payloads() {
  stale=0
  unregistered=$(unregistered_fixtures)
  if [ -n "$unregistered" ]; then
    echo "spec-payloads: fixture files not registered in src/core/test/spec-fixtures.util.ts:" >&2
    printf '  %s\n' $unregistered >&2
    stale=1
  fi
  for suite in $SUITES; do
    if ! golden "$suite" | jq -e --slurpfile committed "$SPEC_DIR/$suite-conformance.json" '. == $committed[0]' > /dev/null; then
      echo "spec-payloads: spec/payload/$suite-conformance.json is stale. Run make spec-payloads." >&2
      stale=1
    fi
    mismatched=$(fixture_mismatches "$suite")
    if [ -n "$mismatched" ]; then
      echo "spec-payloads: the jq payload builder disagrees with spec/payload/$suite.json on:" >&2
      printf '  %s\n' $mismatched >&2
      stale=1
    fi
  done
  if [ "$stale" -ne 0 ]; then
    exit "$EXIT_STALE"
  fi
  echo "spec-payloads: goldens current; jq builder matches every payload fixture; every fixture file registered"
}

case "${1:-}" in
  write) write_goldens ;;
  check) check_payloads ;;
  *)
    echo "usage: spec-payloads.sh write|check" >&2
    exit "$EXIT_USAGE"
    ;;
esac
