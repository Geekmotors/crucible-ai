#!/bin/sh
set -eu

HARNESS_DIR=$(cd "$(dirname "$0")" && pwd)
REPO_DIR=$(cd "$HARNESS_DIR/../../.." && pwd)
CASES_DIR=$REPO_DIR/e2e/ext/fixtures
SCHEMA_DIR=$REPO_DIR/schemas
SPEC_DIR=$REPO_DIR/spec
HARNESS_CONFIG=$REPO_DIR/e2e/crucible.config.json
REGISTRY=$REPO_DIR/src/core/test/spec-fixtures.util.ts
SUITES="coherent extract"
SENTINEL_KEY=sk-spec-sentinel-key
DEFAULT_KEY_ENV=CRUCIBLE_JUDGE_KEY
REQUEST_GOLDENS=$SPEC_DIR/provider/request-conformance.json
EXIT_STALE=1
EXIT_USAGE=2

suite_defs() {
  cat "$HARNESS_DIR/payload-sections.jq" "$HARNESS_DIR/$1-payload.jq"
}

payload_golden() {
  jq --arg suite "$1" "$(suite_defs "$1")
{
  area: \"payload\",
  operation: \$suite,
  description: \"Generated by e2e/ext/conformance/spec-goldens.sh from e2e/ext/fixtures/\(\$suite)-conformance.json with the conformance harness's jq payload builder. Do not edit; run make spec-goldens.\",
  cases: [
    .cases[]
    | {
        id: \"payload-\(\$suite)-conformance-\(.id)\",
        description: \"The \(\$suite) conformance case \(.id) builds the payload the jq harness sends.\",
        input: ({ facts: .state, response } + (if \$suite == \"coherent\" then { claim } else { target, type, mode } end)),
        expect: { text: (. | ${1}_payload) }
      }
  ]
}" "$CASES_DIR/$1-conformance.json"
}

request_variants() {
  printf '%s\n' \
    "coherent harness-config $HARNESS_CONFIG" \
    "extract harness-config $HARNESS_CONFIG" \
    'coherent openai-named-key {"provider":"openai","model":"gpt-5-mini","apiKeyEnv":"OPENAI_JUDGE_KEY"}' \
    'coherent compatible-trailing-slash {"provider":"openai-compatible","model":"local-judge","baseUrl":"https://gateway.example.com/v1/"}' \
    'coherent compatible-keyless {"provider":"openai-compatible","model":"llama3.1:8b","baseUrl":"http://localhost:11434/v1"}'
}

harness_request() {
  suite=$1
  config_file=$2
  key_env=$3
  key_value=$4
  if [ -n "$key_value" ]; then
    env "$key_env=$key_value" \
      CONFORMANCE_SUITES="$suite" \
      CONFORMANCE_CASES_DIR="$WORK_DIR/cases" \
      CONFORMANCE_SCHEMA_DIR="$SCHEMA_DIR" \
      CONFORMANCE_JUDGE_CONFIG="$config_file" \
      sh "$HARNESS_DIR/conformance.sh" request "$suite" 0
  else
    env -u "$key_env" \
      CONFORMANCE_SUITES="$suite" \
      CONFORMANCE_CASES_DIR="$WORK_DIR/cases" \
      CONFORMANCE_SCHEMA_DIR="$SCHEMA_DIR" \
      CONFORMANCE_JUDGE_CONFIG="$config_file" \
      sh "$HARNESS_DIR/conformance.sh" request "$suite" 0
  fi
}

request_case() {
  suite=$1
  variant=$2
  config_file=$3
  key_env=$(jq -r --arg default "$DEFAULT_KEY_ENV" '.apiKeyEnv // $default' "$config_file")
  key_value=$SENTINEL_KEY
  if [ "$variant" = compatible-keyless ]; then
    key_value=
  fi
  request=$(harness_request "$suite" "$config_file" "$key_env" "$key_value")
  jq -n \
    --arg suite "$suite" \
    --arg variant "$variant" \
    --arg key_env "$key_env" \
    --arg key_value "$key_value" \
    --rawfile system "$SCHEMA_DIR/$suite.md" \
    --slurpfile judge "$config_file" \
    --slurpfile matrix "$CASES_DIR/$suite-conformance.json" \
    --argjson request "$request" \
    "$(suite_defs "$suite")
def harness_only_removed:
  if \$judge[0].provider != \"openrouter\" then .
  elif \$judge[0].meta | type == \"object\" and has(\"usage\") then .body.usage = \$judge[0].meta.usage
  else del(.body.usage) end;
def envelope_note:
  if \$judge[0].provider == \"openrouter\" then \", without the usage member only the harness adds for openrouter\" else \"\" end;
{
  id: \"provider-request-conformance-\(\$suite)-\(\$variant)\",
  description: \"The request the jq conformance harness builds for the first \(\$suite) conformance case with the \(\$variant) judge config\(envelope_note).\",
  input: {
    config: \$judge[0],
    env: (if \$key_value == \"\" then {} else { (\$key_env): \$key_value } end),
    system: \$system,
    prompt: (\$matrix[0].cases[0] | ${suite}_payload)
  },
  expect: { value: (\$request | harness_only_removed) }
}"
}

request_golden() {
  WORK_DIR=$(mktemp -d)
  trap 'rm -rf "$WORK_DIR"' EXIT
  mkdir "$WORK_DIR/cases"
  for suite in $SUITES; do
    cp "$CASES_DIR/$suite-conformance.json" "$WORK_DIR/cases/$suite.json"
  done
  request_variants > "$WORK_DIR/variants"
  : > "$WORK_DIR/requests"
  while read -r suite variant config; do
    case "$config" in
      /*) config_file=$config ;;
      *)
        config_file=$WORK_DIR/$variant.json
        printf '%s\n' "$config" > "$config_file"
        ;;
    esac
    request_case "$suite" "$variant" "$config_file" >> "$WORK_DIR/requests"
  done < "$WORK_DIR/variants"
  built=$(jq -s 'length' "$WORK_DIR/requests")
  expected=$(wc -l < "$WORK_DIR/variants" | tr -d ' ')
  if [ "$built" -ne "$expected" ]; then
    echo "spec-goldens: built $built of $expected request goldens" >&2
    exit "$EXIT_STALE"
  fi
  jq -s '{
    area: "provider",
    operation: "request",
    description: "Generated by e2e/ext/conformance/spec-goldens.sh with the conformance harness'"'"'s own request builder (conformance.sh request). Do not edit; run make spec-goldens.",
    cases: .
  }' "$WORK_DIR/requests"
}

fixture_mismatches() {
  jq -r "$(suite_defs "$1")
.cases[]
| select((.input + { state: ((.input.facts // []) + (.input.callFacts // [])) } | ${1}_payload) != .expect.text)
| .id" "$SPEC_DIR/payload/$1.json"
}

write_goldens() {
  for suite in $SUITES; do
    payload_golden "$suite" > "$SPEC_DIR/payload/$suite-conformance.json.tmp"
    mv "$SPEC_DIR/payload/$suite-conformance.json.tmp" "$SPEC_DIR/payload/$suite-conformance.json"
  done
  request_golden > "$REQUEST_GOLDENS.tmp"
  mv "$REQUEST_GOLDENS.tmp" "$REQUEST_GOLDENS"
  (cd "$REPO_DIR" && npx prettier --log-level warn --write spec/payload/*-conformance.json spec/provider/request-conformance.json)
}

unregistered_fixtures() {
  (cd "$REPO_DIR" && find spec -name '*.json' ! -path spec/fixture.schema.json ! -path spec/surface.schema.json ! -path spec/surface.json | sort) | while read -r file; do
    grep -q "'../../../$file'" "$REGISTRY" || echo "$file"
  done
}

check_goldens() {
  stale=0
  unregistered=$(unregistered_fixtures)
  if [ -n "$unregistered" ]; then
    echo "spec-goldens: fixture files not registered in src/core/test/spec-fixtures.util.ts:" >&2
    printf '  %s\n' $unregistered >&2
    stale=1
  fi
  for suite in $SUITES; do
    if ! payload_golden "$suite" | jq -e --slurpfile committed "$SPEC_DIR/payload/$suite-conformance.json" '. == $committed[0]' > /dev/null; then
      echo "spec-goldens: spec/payload/$suite-conformance.json is stale. Run make spec-goldens." >&2
      stale=1
    fi
    mismatched=$(fixture_mismatches "$suite")
    if [ -n "$mismatched" ]; then
      echo "spec-goldens: the jq payload builder disagrees with spec/payload/$suite.json on:" >&2
      printf '  %s\n' $mismatched >&2
      stale=1
    fi
  done
  if ! request_golden | jq -e --slurpfile committed "$REQUEST_GOLDENS" '. == $committed[0]' > /dev/null; then
    echo "spec-goldens: spec/provider/request-conformance.json is stale. Run make spec-goldens." >&2
    stale=1
  fi
  if [ "$stale" -ne 0 ]; then
    exit "$EXIT_STALE"
  fi
  echo "spec-goldens: payload and request goldens current; jq builder matches every payload fixture; every fixture file registered"
}

case "${1:-}" in
  write) write_goldens ;;
  check) check_goldens ;;
  *)
    echo "usage: spec-goldens.sh write|check" >&2
    exit "$EXIT_USAGE"
    ;;
esac
